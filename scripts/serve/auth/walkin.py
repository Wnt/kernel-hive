"""The walk-in plane's auth half: the role, self-registration, and the switch.

`docs/lab/WALKIN-BRIEF.md` §5 is the spec; `docs/lab/walkin/CONTRACT-LEDGER.md`
§3/§4 freezes the routes and the state shape. Three things live here:

  * **The switch** — Closed / Invited only / Open, persisted in auth-state.json
    under an env floor that can only LOWER it. A kill switch that lived in
    memory would re-open the plane on the next service restart, which is the one
    failure mode it may not have.
  * **Self-registration** — passkey-first, usernameless, no email, no PII. The
    account is a role, an autogenerated handle and nothing else.
  * **The teardown** — dropping to Closed refuses inflow FIRST and only then
    tears down, so nothing re-enters behind it.

The pool itself belongs to the broker (`scripts/serve/walkin/`). This module
calls it and never reimplements it; with no broker bound (it lands on its own
schedule) the switch still refuses inflow and drops sessions, and says so.
"""

from __future__ import annotations

import os
import sys
import threading
import time
from pathlib import Path

from .service import AuthError, RateLimiter, _device_label, _new_user_id
from .store import iso, now

# Closed < invited < open. Comparisons are by INDEX in this tuple, so the env
# floor is a min() and nothing has to reason about which string outranks which.
ACCESS_ORDER = ("closed", "invited", "open")
# The reason code a live session is closed with, so the SPA renders "walk-in
# access is currently closed" rather than a generic connection error
# (ledger §3.1). It sits beside streamhost's existing SESSION_REJECTED.
REASON_CLOSED = "WALKIN_CLOSED"
# Registration throttles (brief §5, ledger decision 7). Deliberately blunt: the
# lever if abuse arrives is proof-of-work, not a finer rate limit.
SIGNUP_WINDOW_SECS = 3600
SIGNUP_PER_IP = 5
ACCOUNT_CAP = 500
IDLE_EXPIRY_DAYS = 90


def _floor_from_env(env: dict | None = None) -> str:
    """The env floor (ledger §4.2). Unset or `0` means closed, whatever the
    switch says; it can only lower the switch, never raise it."""
    raw = (env if env is not None else os.environ).get("WALKIN_OPEN")
    value = (raw or "").strip().lower()
    if value in ("", "0", "false", "no", "off", "closed"):
        return "closed"
    if value == "invited":
        return "invited"
    return "open"


def _lower_of(a: str, b: str) -> str:
    return ACCESS_ORDER[min(ACCESS_ORDER.index(a), ACCESS_ORDER.index(b))]


class WalkinService:
    """Policy for the walk-in role. One per AuthService; safe from any thread."""

    def __init__(self, store, ceremonies, tickets=None, broker=None, env=None, manifest_path=None):
        self.store = store
        self.ceremonies = ceremonies
        self.tickets = tickets
        self.broker = broker
        self._env = env
        # The rendered gallery manifest, projected per request. Resolved from
        # WEBROOT — the serving unit already sets it (serve/config.py) — so the
        # projection needs no new wiring at the call site.
        webroot = (env if env is not None else os.environ).get("WEBROOT")
        self.manifest_path = manifest_path or (Path(webroot) / "gallery-manifest.json" if webroot else None)
        self.limiter = RateLimiter(window=SIGNUP_WINDOW_SECS, limit=SIGNUP_PER_IP)
        self._lock = threading.Lock()

    def bind_broker(self, broker) -> None:
        """Wire the pool broker once it exists. Late binding on purpose: the
        broker lands as its own lane and the switch must work without it."""
        self.broker = broker

    # ---- where the switch is standing --------------------------------------

    @property
    def env_floor(self) -> str:
        return _floor_from_env(self._env)

    def stored_access(self) -> str:
        access = self.store.snapshot()["walkin"]["access"]
        return access if access in ACCESS_ORDER else "closed"

    def access(self) -> str:
        """The EFFECTIVE position: the switch, lowered by the env floor."""
        return _lower_of(self.stored_access(), self.env_floor)

    def draining(self) -> bool:
        return bool(self.store.snapshot()["walkin"]["drain"])

    def is_open_to(self, user: dict | None) -> bool:
        """Whether this caller may reach the walk-in plane at all."""
        access = self.access()
        if access == "open":
            return True
        if access == "invited":
            return bool(user) and user["role"] in ("admin", "viewer")
        return False

    def require_reachable(self, user: dict | None) -> None:
        if not self.is_open_to(user):
            raise AuthError("walkin_closed", status=403)

    def require_signin(self, user: dict) -> None:
        """Called on the login path: a walk-in account cannot sign in while the
        plane is closed to it, even holding a valid passkey."""
        if user.get("role") == "walkin" and self.access() != "open":
            raise AuthError("walkin_closed", status=403)

    def public_state(self) -> dict:
        """The auth half of GET /walkin/state; the broker merges `pools` in."""
        access = self.access()
        return {
            "access": access,
            "drain": self.draining(),
            "notice": "Walk-in access is currently closed." if access == "closed" else "",
        }

    # ---- moving the switch -------------------------------------------------

    def set_access(self, admin: dict, access: str) -> dict:
        """Move the switch, tearing the plane down when it lands on Closed.

        The ORDER is the point (brief §5.1). Inflow is refused first — the store
        write below is what makes signup, sign-in and /walkin/claim start
        answering 403 — and only then does anything get torn down, so a client
        disconnected in step 3 cannot re-handshake in behind step 4.
        """
        if access not in ACCESS_ORDER:
            raise AuthError("access must be closed, invited or open")
        with self._lock:
            before = self.stored_access()
            live = self.live_sessions()
            # 1. Refuse inflow. Persisted, so a restart cannot undo it.
            with self.store.mutate() as doc:
                block = doc["walkin"]
                block["access"] = access
                block["audit"].append({"at": iso(now()), "admin": admin["id"], "from": before, "to": access})
            if _lower_of(access, self.env_floor) != "closed":
                self._call_broker("refill", tolerate_missing=True)
                return {"access": self.access(), "disconnected": 0}
            return {"access": self.access(), **self._tear_down(live)}

    def _tear_down(self, live: int) -> dict:
        """Steps 2-4 of the drop to Closed. Every step runs even if an earlier
        one failed — a half-finished teardown leaves clones alive — and the
        failures are raised together once the work is done."""
        failed: list[str] = []
        # 2. Revoke outstanding walk-in tickets before killing anything, so a
        #    disconnected client cannot re-handshake into its old clone.
        if self.tickets is not None:
            self.tickets.revoke_all()
        # 3. Close the live sessions with the distinct reason code, and drop the
        #    browser sessions behind them so the cookies are dead too.
        self._call_broker("close_sessions", REASON_CLOSED, failed=failed)
        dropped = self._drop_walkin_sessions()
        # 4. Empty the pool.
        self._call_broker("kill_all_clones", failed=failed)
        if failed:
            raise AuthError(
                f"walk-in access is closed, but the teardown failed: {', '.join(failed)}",
                status=500,
            )
        return {"disconnected": max(live, dropped)}

    def set_drain(self, admin: dict, drain: bool) -> dict:
        """The softer sibling: refuse new claims, let sessions in flight finish.
        It is NOT the kill switch and tears nothing down."""
        with self.store.mutate() as doc:
            doc["walkin"]["drain"] = bool(drain)
            doc["walkin"]["audit"].append(
                {"at": iso(now()), "admin": admin["id"], "from": "drain", "to": str(bool(drain))}
            )
        self._call_broker("set_drain", bool(drain), tolerate_missing=True)
        return {"ok": True, "drain": bool(drain)}

    def status(self) -> dict:
        """GET /auth/walkin/status (ledger §3)."""
        snap = self.store.snapshot()["walkin"]
        return {
            "access": self.access(),
            "stored": self.stored_access(),
            "envFloor": self.env_floor,
            "drain": bool(snap["drain"]),
            "sessions": self.live_sessions(),
            "pools": self._call_broker("pools", tolerate_missing=True) or [],
            "accounts": len(snap["accounts"]),
            "audit": snap["audit"][-20:],
        }

    def live_sessions(self) -> int:
        count = self._call_broker("live_sessions", tolerate_missing=True)
        if isinstance(count, int):
            return count
        doc = self.store.snapshot()
        ids = {u["id"] for u in doc["users"] if u["role"] == "walkin"}
        return sum(1 for s in doc["sessions"] if s["userId"] in ids)

    # ---- self-registration -------------------------------------------------

    def begin_signup(self, client_ip: str) -> tuple[str, dict]:
        """Start the passkey ceremony for a brand-new walk-in account.

        No name, no email, nothing typed: the only identity is the credential,
        and the handle is display. The handle offered to the authenticator is a
        CANDIDATE — the authoritative allocation happens under the store lock at
        finish, so two simultaneous signups cannot both become `bold-turing`.
        """
        if self.access() != "open":
            raise AuthError("walkin_closed", status=403)
        self.limiter.check(f"walkin-signup:{client_ip}")
        self._check_cap()
        uid = _new_user_id()
        candidate = _generate_handle(self._taken_handles())
        return self.ceremonies.begin_registration(
            user_id=uid.encode("ascii"),
            name=candidate,
            display_name=candidate,
            existing=[],
            meta={"userId": uid, "walkin": True},
        )

    def finish_signup(self, cid: str, response: dict, ip: str, user_agent: str) -> tuple[dict, str, str]:
        try:
            cred, meta = self.ceremonies.finish_registration(cid, response)
        except AuthError:
            raise
        except Exception as exc:
            sys.stderr.write(f"[auth] walk-in registration rejected: {type(exc).__name__}: {exc}\n")
            raise AuthError("passkey registration failed", status=400) from exc
        if not meta.get("walkin"):
            raise AuthError("passkey registration failed", status=400)
        # Re-check at COMPLETION, not just at begin: a ceremony can sit open for
        # minutes, and the switch may have moved in between.
        if self.access() != "open":
            raise AuthError("walkin_closed", status=403)
        from .passkeys import credential_id_b64, credential_to_b64

        handle = self._allocate_account(meta["userId"])
        self.store.add_credential(
            meta["userId"], credential_id_b64(cred), credential_to_b64(cred), _device_label(user_agent)
        )
        user = self.store.user(meta["userId"])
        return user, self.store.new_session(user["id"], ip, user_agent), handle

    def _allocate_account(self, user_id: str) -> str:
        """Mint the user row and its handle in ONE critical section.

        Handle uniqueness is a claim on a shared thing, so it is allocated
        inside the same lock that writes the file — never checked and then
        created (OPERATING-RULES rule 7).
        """
        with self.store.mutate() as doc:
            if len(doc["walkin"]["accounts"]) >= ACCOUNT_CAP:
                raise AuthError("walk-in registration is full right now; try later", status=429)
            taken = {a["handle"] for a in doc["walkin"]["accounts"].values()}
            handle = _generate_handle(taken)
            stamp = iso(now())
            doc["users"].append(
                {"id": user_id, "name": handle, "role": "walkin", "createdAt": stamp, "lastSeenAt": None}
            )
            doc["walkin"]["accounts"][user_id] = {
                "handle": handle,
                "createdAt": stamp,
                "lastSeenAt": None,
            }
        return handle

    def _taken_handles(self) -> set[str]:
        return {a["handle"] for a in self.store.snapshot()["walkin"]["accounts"].values()}

    def _check_cap(self) -> None:
        if len(self.store.snapshot()["walkin"]["accounts"]) >= ACCOUNT_CAP:
            raise AuthError("walk-in registration is full right now; try later", status=429)

    # ---- purging -----------------------------------------------------------

    def purge(self, older_than_days: int = IDLE_EXPIRY_DAYS) -> dict:
        """Delete walk-in accounts idle longer than `older_than_days`.

        Idle is measured from lastSeenAt, or from createdAt for an account that
        never came back. Only walk-ins: an invited account is never reaped by a
        clock.
        """
        days = max(1, int(older_than_days or IDLE_EXPIRY_DAYS))
        cutoff = time.time() - days * 86400
        stale = []
        for user_id, account in self.store.snapshot()["walkin"]["accounts"].items():
            seen = account.get("lastSeenAt") or account.get("createdAt") or ""
            if _epoch(seen) < cutoff:
                stale.append(user_id)
        for user_id in stale:
            self.store.delete_user(user_id)
            with self.store.mutate() as doc:
                doc["walkin"]["accounts"].pop(user_id, None)
        return {"purged": len(stale)}

    # ---- what a walk-in may see --------------------------------------------

    def manifest(self, own: dict | None = None) -> dict:
        """GET /walkin/manifest.json — the allowlist projection (brief §5.3).

        Read from the SAME rendered gallery manifest the invited plane is
        served, so the exhibition prose can never drift between the two planes;
        gate.walkin_manifest is what decides which of its fields survive.
        """
        from . import gate

        return gate.walkin_manifest(self._gallery_entries(), own)

    def _gallery_entries(self) -> list[dict]:
        import json

        path = self.manifest_path
        if path is None or not path.is_file():
            # No manifest published is an empty museum, never the whole one:
            # failing open here would publish every field of every station.
            sys.stderr.write(f"[auth] walk-in manifest: {path} is not readable\n")
            return []
        try:
            return json.loads(path.read_text()).get("entries", [])
        except Exception as exc:  # noqa: BLE001
            sys.stderr.write(f"[auth] walk-in manifest is unreadable: {exc}\n")
            return []

    def accounts(self) -> list[dict]:
        snap = self.store.snapshot()["walkin"]["accounts"]
        return [{"userId": uid, **account} for uid, account in sorted(snap.items())]

    # ---- helpers -----------------------------------------------------------

    def _drop_walkin_sessions(self) -> int:
        with self.store.mutate() as doc:
            ids = {u["id"] for u in doc["users"] if u["role"] == "walkin"}
            keep = [s for s in doc["sessions"] if s["userId"] not in ids]
            dropped = len(doc["sessions"]) - len(keep)
            doc["sessions"] = keep
        return dropped

    def _call_broker(self, name: str, *args, failed: list | None = None, tolerate_missing: bool = False):
        """Call the pool broker, loudly. A missing broker is tolerated only
        where the caller says so; a broker that RAISED is always reported."""
        fn = getattr(self.broker, name, None) if self.broker is not None else None
        if fn is None:
            if not tolerate_missing and failed is not None:
                sys.stderr.write(f"[auth] walk-in teardown: no broker bound for {name}()\n")
            return None
        try:
            return fn(*args)
        except Exception as exc:  # noqa: BLE001 — reported, never swallowed
            sys.stderr.write(f"[auth] walk-in broker {name}() failed: {type(exc).__name__}: {exc}\n")
            if failed is not None:
                failed.append(f"{name}(): {exc}")
            return None


def _generate_handle(taken: set[str]) -> str:
    """Lane 3's generator (ledger §4.3), imported at the call site.

    The import is deferred so that this module loads on a checkout where
    `auth/handles/` has not landed yet; the moment a signup is actually
    attempted, a missing generator is a hard failure rather than a silent
    fallback to some second naming scheme.
    """
    from .handles import generate_handle

    return generate_handle(taken)


def _epoch(stamp: str) -> float:
    try:
        return time.mktime(time.strptime(stamp, "%Y-%m-%dT%H:%M:%SZ")) - time.timezone
    except (ValueError, TypeError):
        return 0.0
